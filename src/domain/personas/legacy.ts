/**
 * 이전 묘묘 설정 (1.0.0~1.4.0). 현재 생성 경로에서는 쓰지 않는다.
 *
 * 생성 작업은 시작할 때 프롬프트 버전을 고정하고(claim_generation), 실패한 작업을 다시 시도해도 그 버전을 그대로 쓴다.
 * 그래서 reading-2.9.0 이전 프롬프트로 시작한 작업을 이어 쓸 때만 이 파일의 설정을 쓴다 (prompts-legacy.ts).
 * 상황별 완성 대사, 판단에 묶인 예시, 말버릇 목록과 횟수 제한은 모두 이 이전 설정에만 있다.
 * 새 캐릭터 설정은 index.ts의 묘묘 2.0.0이며, 이 파일의 내용을 가져다 쓰지 않는다. 고치지 않는다.
 */

/**
 * 말버릇과 횟수 상한. 이전 지시가 프롬프트에 그대로 옮기던 기록이다.
 * 묘묘 2.0.0부터는 말버릇 목록을 두지 않고, 검사도 말버릇 횟수를 세지 않는다 (이전 작업을 이어 쓸 때도 세지 않는다).
 */
export interface Catchphrase {
  /** 프롬프트에 보여 주는 표현. */
  readonly text: string;
  /** 셀 때 찾는 글자. */
  readonly pattern: string;
  /** 단어 첫머리에 올 때만 센다. '어라'를 셀 때 '들어라', '적어라' 같은 말끝은 세지 않으려고 쓴다. */
  readonly wordStart?: boolean;
  /** frequent: 자주 써도 되는 말, occasional: 가끔만 쓰는 약한 놀림. */
  readonly kind: "frequent" | "occasional";
  /** 최초 풀이 전체에서 쓸 수 있는 횟수. */
  readonly maxPerReading: number;
  /** 후속 답변 하나(질문 하나)에서 쓸 수 있는 횟수. */
  readonly maxPerAnswer: number;
}

/**
 * 말투 예시. 같은 판단을 밋밋하게 말한 문장(flat)과 캐릭터답게 말한 문장(lines)을 나란히 둔다.
 * 그 판단을 뒷받침하는 재료가 있을 때만 이런 방식으로 말하며, 문장을 그대로 붙여 넣지 않는다.
 */
export interface PersonaExample {
  readonly when: string;
  /** 같은 판단을 캐릭터 없이 말한 문장. 이렇게 쓰지 말라는 비교용이다. */
  readonly flat?: string;
  readonly lines: readonly string[];
  /**
   * 이 예시를 넣을 프롬프트. 없으면 프롬프트에 넣지 않고 문서(docs/personas)와 평가 자료에만 둔다.
   * 입력이 너무 길어지지 않게 대표 예시만 넣는다. (이전 설정 1.0.0은 이 값 없이 모든 예시를 넣는다.)
   */
  readonly prompt?: "reading" | "followup" | "both";
}

/**
 * 재료를 캐릭터의 말로 바꾸는 시범 (1.2.0부터). 입력에 들어가는 재료 한 덩어리를 그대로 옮겨 적은 말(실패)과
 * 캐릭터가 같은 뜻을 자기 말로 한 것을 나란히 둔다. 모델이 재료 문장을 반말로 옮겨 적는 것을 막으려고 둔다.
 * 〈 〉 자리는 실제 사람의 재료 값으로 바뀌어야 하는 자리다 (예시 값이 다른 사람에게 옮겨 가지 않게).
 */
export interface PersonaDemonstration {
  readonly use: "reading" | "followup";
  readonly situation: string;
  /** 입력 재료를 줄여 적은 것. */
  readonly material: string;
  /** 재료를 순서대로 옮겨 적은 말. 이렇게 쓰지 말라는 비교용이다. */
  readonly transcribed: readonly string[];
  readonly lines: readonly string[];
  /** 무엇을 바꿨는지. */
  readonly notes: readonly string[];
}

/** 설명하는 본문에서 캐릭터의 성격이 드러나는 자리 (무엇을 먼저 짚고, 어떻게 인정하고, 어떻게 참견하는지). */
export interface PersonaDelivery {
  readonly what: string;
  readonly how: string;
  /** 한쪽 프롬프트에만 해당하는 방식. 없으면 둘 다. */
  readonly use?: "reading" | "followup";
}

/** 이전 설정의 모양. 지시 블록(prompts-legacy.ts)이 읽는 칸만 둔다. 화면과 고정 문장은 현재 설정(index.ts)을 쓴다. */
export interface LegacyPersona {
  readonly id: string;
  readonly version: string;
  readonly name: string;
  readonly role: string;
  readonly intro: string;
  readonly speech: "casual" | "polite";
  readonly tone: readonly string[];
  readonly delivery?: readonly PersonaDelivery[];
  readonly moments: readonly string[];
  readonly sceneStyle: readonly string[];
  readonly examples: readonly PersonaExample[];
  readonly demonstrations?: readonly PersonaDemonstration[];
  readonly voiceSamples?: readonly string[];
  readonly catchphrases: readonly Catchphrase[];
  readonly emojiLimit: { readonly perReading: number; readonly perAnswer: number };
}

