  readonly speech: "casual" | "polite";
  readonly tone: readonly string[];
  /** 설명하는 본문에서 성격을 드러내는 방식 (1.1.0부터). */
  readonly delivery?: readonly PersonaDelivery[];
  /** 상황마다 달라지는 반응: 진지한 고민, 오류 정정, 칭찬과 지적을 받았을 때. */
