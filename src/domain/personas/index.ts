/**
 * 캐릭터 설정은 이 파일에서만 관리한다. 프롬프트, 맛보기, 후속 질문의 고정 안내, 화면 표시가 모두 여기서 읽는다.
 * (1.x로 시작한 작업의 말버릇 횟수 검사도 여기서 읽는다. 2.1.0부터는 말버릇·이모티콘을 세지 않는다.)
 * 캐릭터는 말하는 방식(말투, 비유, 반응, 설명의 리듬)만 정한다. 계산값, 해석 규칙, 근거, 기간 판단, 판단 범위는
 * 상품 규칙과 작성 재료가 정하며, 캐릭터를 바꿔도 판단 재료는 그대로다.
 * 설정을 바꿀 때는 이전 버전을 고치지 않고 남겨 둔다. 생성 작업은 시작할 때 고정한 프롬프트 버전에 맞는 설정을 쓴다
 * (prompts.ts의 personaVersionFor → findPersona(id, version)).
 * 사람이 읽는 설정 문서: docs/personas/myomyo.md, 비교 예시와 평가 기준: docs/personas/myomyo-evaluation.md
 */

