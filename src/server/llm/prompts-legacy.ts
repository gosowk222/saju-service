/**
 * 작성 재료의 중복을 덜어 낸다 (reading-2.7.0, followup-2.7.0). 뜻은 그대로다.
 * - 같은 명리 근거(lore)와 이유(basis)는 처음 나온 해석에만 넣는다. 한 사주에서 같은 근거 한 줄이 열 번 넘게 들어가
 *   여러 주제가 같은 비율·글자 설명을 되풀이하게 만들었다 (2026-11-11 실제 사례: 같은 lore 15번).
 * - 여러 해석에 같은 주의사항(caveats)은 commonCaveats로 한 번만 넣는다.
 * 검사는 이 입력이 아니라 계획 전체의 재료로 하므로, 덜어 낸 근거를 말해도 검사에 걸리지 않는다.
 */
function materialInput(groups: readonly (readonly InterpretationStatement[])[]) {
  const caveatCount = new Map<string, number>();
  for (const statement of groups.flat()) for (const caveat of new Set(statement.caveats)) caveatCount.set(caveat, (caveatCount.get(caveat) ?? 0) + 1);
  const common = [...caveatCount].filter(([, count]) => count > 1).map(([caveat]) => caveat);
  const shared = new Set(common);
  const seenLore = new Set<string>();
  const seenBasis = new Set<string>();
  const fresh = (items: readonly string[] | undefined, seen: Set<string>) => {
    const kept = (items ?? []).filter((item) => !seen.has(item));
    for (const item of kept) seen.add(item);
    return kept;
  };
  const one = (statement: InterpretationStatement) => {
    const lore = fresh(statement.lore, seenLore);
    return {
      ref: statement.ref,
      aspect: statement.aspect ?? null,
      text: statement.text,
      status: statement.status,
      basis: fresh(statement.basis, seenBasis),
      upside: statement.upside ?? null,
      weakness: statement.weakness ?? null,
      action: statement.action ?? null,
      counterNote: statement.counterNote ?? null,
      compare: statement.compare ?? null,
      caveats: statement.caveats.filter((caveat) => !shared.has(caveat)),
      ...(lore.length ? { lore } : {}),
    };
  };
  return { commonCaveats: common, groups: groups.map((group) => group.map(one)) };
}

