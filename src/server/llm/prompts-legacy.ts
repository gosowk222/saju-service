/**
 * 이전 최초 풀이 지시 (reading-1.0.0 ~ reading-2.9.0)와 이전 캐릭터 블록. 현재 생성 경로(reading-3.0.0)는 이 파일을 쓰지 않는다.
 *
 * 생성 작업은 시작할 때 프롬프트 버전을 고정하고, 실패해 다시 시도해도 그 버전을 쓴다 (claim_generation의 coalesce).
 * 그래서 이전 버전으로 시작한 작업을 이어 쓸 수 있도록 지시를 그대로 남겨 둔다. 내용을 고치지 않는다.
 * 이 지시들의 말버릇 상한, 비교 예시, 시범, 말투 견본, '묘묘다운 순간'은 이전 설정의 기록이며 현재 규칙이 아니다.
 * 캐릭터 설정은 이 버전들과 함께 쓰던 이전 설정(src/domain/personas/legacy.ts)을 받는다.
 * 버전별 변경 이유: docs/READING_QUALITY.md 19~22절, docs/LLM_OPERATIONS.md
 */

type LegacyV1Args = Omit<ReadingPromptArgs, "persona"> & { readonly persona: LegacyPersona };
type LegacyV2Args = Omit<ReadingPromptV2Args, "persona"> & { readonly persona: LegacyPersona };

/** 이전 지시는 그 버전과 함께 쓰던 이전 캐릭터 설정만 받는다. 현재 설정이 들어오면 지시가 섞이므로 멈춘다. */
function legacyArgs<T extends ReadingPromptArgs | ReadingPromptV2Args>(args: T): Omit<T, "persona"> & { readonly persona: LegacyPersona } {
  if (!("tone" in args.persona)) throw new Error("persona_version_mismatch: 이전 지시에는 그 버전과 함께 쓰던 이전 캐릭터 설정이 필요합니다.");
  return args as Omit<T, "persona"> & { readonly persona: LegacyPersona };
}

/** 캐릭터 설정(src/domain/personas)을 프롬프트로 옮긴다. 설정을 프롬프트마다 복사하지 않고 여기서 한 번에 만든다. */
function personaBlock(persona: LegacyPersona): string {
  const phrases = (kind: "frequent" | "occasional") =>
    persona.catchphrases
      .filter((phrase) => phrase.kind === kind)
      .map((phrase) => `${phrase.text}(${phrase.maxPerReading}/${phrase.maxPerAnswer})`)
      .join(", ");
  return [
    `캐릭터 이름: ${persona.name}`,
    `역할: ${persona.role}`,
    `소개: ${persona.intro}`,
    `말씨: ${persona.speech === "casual" ? "반말" : "존댓말"}. 사용자는 입력의 address.call로 부른다.`,
    "말하는 방식:",
    ...persona.tone.map((line) => `- ${line}`),
    ...(persona.moments.length ? ["상황에 따라 달라지는 반응:", ...persona.moments.map((line) => `- ${line}`)] : []),
    ...(persona.catchphrases.length
      ? [
          "말버릇 (괄호 안은 최초 풀이 전체 / 후속 답변 하나에서 쓸 수 있는 최대 횟수. 넘기면 검사에서 다시 쓰게 된다):",
          `- 자주 써도 되는 말: ${phrases("frequent")}`,
          `- 가끔만 쓰는 약한 놀림: ${phrases("occasional")}`,
          `- 그림 이모티콘: ${persona.emojiLimit.perReading}개 / ${persona.emojiLimit.perAnswer}개까지`,
        ]
      : []),
    ...(persona.examples.length
      ? [
          "말투 예시 (그 판단을 뒷받침하는 재료가 있을 때만 이런 식으로 말한다. 문장을 그대로 붙여 넣지 않는다):",
          ...persona.examples.flatMap((example) => [`- ${example.when}:`, ...example.lines.map((line) => `  "${line}"`)]),
        ]
      : []),
  ].join("\n");
}

